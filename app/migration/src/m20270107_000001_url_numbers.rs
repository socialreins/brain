use sea_orm_migration::prelude::*;

#[derive(DeriveMigrationName)]
pub struct Migration;

// A number for what the web app puts in an address (`/t/<team>/lists/12`, `?item=4821`), as
// `posts.number` is for posts: one counter per table over every team, the UUID stays the primary
// key and every foreign key stays as it is. Existing rows are numbered in the order they were made
// (the id breaks ties), then the counter carries on after the largest. Identity "by default" lets
// a dump be restored with its numbers.
// `lock_timeout`: each ALTER waits for open transactions on its table and everything behind it
// waits for the ALTER; a timeout fails this boot instead, and the old instance goes on serving.
// The locks are held to the end of the migration, so the backfills below add up: they are one
// UPDATE per table.
const TABLES: [(&str, &str); 7] = [
    ("post_lists", "created_at"),
    ("automations", "created_at"),
    ("broadcasts", "created_at"),
    ("newsletters", "created_at"),
    ("inboxes", "created_at"),
    ("inbox_items", "created_at"),
    ("contacts", "first_seen_at"),
];

fn up(table: &str, made: &str) -> String {
    format!(
        "ALTER TABLE {table} ADD COLUMN number bigint;
UPDATE {table} t SET number = n.n
  FROM (SELECT id, row_number() OVER (ORDER BY {made}, id) AS n FROM {table}) n
  WHERE n.id = t.id;
ALTER TABLE {table} ALTER COLUMN number SET NOT NULL,
  ALTER COLUMN number ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('{table}', 'number'),
  COALESCE((SELECT max(number) FROM {table}), 0) + 1, false);
CREATE UNIQUE INDEX {table}_number_key ON {table} (number);"
    )
}

#[async_trait::async_trait]
impl MigrationTrait for Migration {
    async fn up(&self, m: &SchemaManager) -> Result<(), DbErr> {
        let db = m.get_connection();
        db.execute_unprepared("SET LOCAL lock_timeout = '10s'")
            .await?;
        for (table, made) in TABLES {
            db.execute_unprepared(&up(table, made)).await?;
        }
        Ok(())
    }

    async fn down(&self, m: &SchemaManager) -> Result<(), DbErr> {
        for (table, _) in TABLES {
            let sql = format!("ALTER TABLE {table} DROP COLUMN IF EXISTS number;");
            m.get_connection().execute_unprepared(&sql).await?;
        }
        Ok(())
    }
}
